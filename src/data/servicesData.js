// Simple search matching using keywords & categories
export function findServiceByQuery(query, lang = "en") {
  if (!query) return null;
  const q = query.toLowerCase().trim();

  // Score match
  let bestMatch = null;
  let highestScore = 0;

  for (const catId in servicesData) {
    const category = servicesData[catId];
    for (const subId in category.subCategories) {
      const sub = category.subCategories[subId];
      let score = 0;

      // 1. Direct title match
      const titleEn = (sub.title.en || "").toLowerCase();
      const titleSi = (sub.title.si || "").toLowerCase();
      const titleTa = (sub.title.ta || "").toLowerCase();

      if (q.includes(titleEn) || titleEn.includes(q)) score += 5;
      if (q.includes(titleSi) || titleSi.includes(q)) score += 5;
      if (q.includes(titleTa) || titleTa.includes(q)) score += 5;

      // 2. Keywords match
      if (sub.keywords) {
        sub.keywords.forEach(kw => {
          const kwLower = kw.toLowerCase();
          if (q.includes(kwLower)) {
            score += 4;
          } else {
            // Partial match
            const words = q.split(/\s+/);
            words.forEach(w => {
              if (w.length > 2 && kwLower.includes(w)) {
                score += 1;
              }
            });
          }
        });
      }

      // 3. Office name match
      const officeEn = (sub.officeName.en || "").toLowerCase();
      const officeSi = (sub.officeName.si || "").toLowerCase();
      const officeTa = (sub.officeName.ta || "").toLowerCase();
      if (q.includes(officeEn) || q.includes(officeSi) || q.includes(officeTa)) {
        score += 2;
      }

      if (score > highestScore) {
        highestScore = score;
        bestMatch = { categoryId: catId, serviceId: subId, data: sub };
      }
    }
  }

  // If score is too low, return null
  if (highestScore < 2) return null;
  return bestMatch;
}

